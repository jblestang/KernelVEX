"""Management of the ``cip-kernel-sec`` git mirror, catalog JSON, and enrichment merge.

Strictly uses ``cip-kernel-sec`` as the single source of truth for kernel CVEs
and optionally merges ``affected-files`` / ``affected-configs`` generated by
``cve-triage enrich``. Rejects any non-CVE or fictional identifiers.
"""

from __future__ import annotations

import json
import os
import re
import subprocess
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

import yaml

from kernelvex import DEFAULT_SEC_BRANCH, DEFAULT_SEC_REPO_URL, KernelVexError
from kernelvex.profile import ProfileName, is_cve_applicable_to_profile

# Enforce real CVE identifiers (CVE-YYYY-NNNN+) and exclude TEST-* fixtures.
_CVE_ID_RE = re.compile(r"^CVE-(?P<year>[0-9]{4})-(?P<num>[0-9]+)$")
_GIT_SHA_RE = re.compile(r"^[0-9a-fA-F]{40}$")

# Prefer libyaml CSafeLoader when available for ~10x faster bulk YAML parsing.
_YAML_LOADER = getattr(yaml, "CSafeLoader", yaml.SafeLoader)


def resolve_cache_dir(cache_dir: Path | str | None = None) -> Path:
    """Resolve the persistent cache directory for git mirrors, catalog, and kmax.

    Resolution order: explicit ``cache_dir`` argument, ``KERNELVEX_CACHE_DIR``
    environment variable, then ``.cache/kernelvex`` under the working directory.
    Inside containers built from the repository ``Dockerfile``, ``KERNELVEX_CACHE_DIR``
    defaults to ``/cache`` so CI runners can mount a persistent volume across jobs.

    Args:
        cache_dir: Optional caller-supplied directory path overriding environment defaults.

    Returns:
        Absolute, user-expanded cache root ``Path`` (directory creation deferred to writers).
    """
    if cache_dir is not None:
        return Path(cache_dir).expanduser().resolve()
    env_dir = os.environ.get("KERNELVEX_CACHE_DIR")
    if env_dir:
        return Path(env_dir).expanduser().resolve()
    return (Path.cwd() / ".cache" / "kernelvex").resolve()


def _parse_cve_id(name: str) -> tuple[int, int]:
    """Validate a real CVE identifier and return ``(year, sequence)`` for sorting.

    Enforces strict ``CVE-YYYY-NNNN+`` formatting to ensure non-standard or
    synthetic identifiers never enter ``catalog.json`` or downstream VEX output.

    Args:
        name: Raw CVE filename stem or YAML identifier.

    Returns:
        Numeric ``(year, sequence)`` tuple enabling chronological sorting.

    Raises:
        KernelVexError: If ``name`` fails real CVE format validation.
    """
    match = _CVE_ID_RE.match(name)
    if match is None:
        raise KernelVexError(f"Invalid CVE identifier {name!r}: expected real CVE-YYYY-NNNN format")
    return (int(match.group("year")), int(match.group("num")))


def _normalize_sec_url(sec_url: str) -> str:
    """Convert existing local directory paths to ``file://`` URIs for shallow fetch.

    Git disables ``--depth 1`` optimization when given a plain local filesystem
    path unless expressed as a ``file://`` URI. Using ``as_uri()`` ensures local
    mirrors and CI fixtures behave identically to HTTPS remotes.

    Args:
        sec_url: Git remote HTTPS/SSH URL or local repository directory path.

    Returns:
        Normalized remote URL or ``file://`` URI string.
    """
    candidate = Path(sec_url)
    if "://" not in sec_url and not sec_url.startswith("git@") and candidate.exists():
        return candidate.resolve().as_uri()
    return sec_url


def _run_git(args: list[str], cwd: Path | None = None) -> str:
    """Execute a git subprocess and raise ``KernelVexError`` on failure.

    Args:
        args: Argument list passed to ``git`` after optional ``-C <cwd>``.
        cwd: Optional repository directory passed via ``git -C``.

    Returns:
        Stripped standard output from ``git``.

    Raises:
        KernelVexError: If ``git`` cannot be launched or exits non-zero.
    """
    cmd = ["git", *(["-C", str(cwd)] if cwd is not None else []), *args]
    try:
        proc = subprocess.run(cmd, capture_output=True, text=True, check=False)
    except OSError as exc:
        raise KernelVexError(f"Failed to invoke git ({cmd}): {exc}") from exc

    if proc.returncode != 0:
        detail = proc.stderr.strip() or proc.stdout.strip() or f"exit code {proc.returncode}"
        raise KernelVexError(f"git command failed ({' '.join(cmd)}): {detail}")
    return proc.stdout.strip()


def _sync_sec_repo(sec_dir: Path, sec_url: str, sec_ref: str) -> str:
    """Clone or shallow-fetch ``cip-kernel-sec`` to ``sec_ref`` and return HEAD SHA.

    Handles both named refs (branches/tags via ``clone --branch``) and pinned
    40-character commit SHAs (via ``init`` + ``fetch --depth 1`` + detached checkout)
    so CI pipelines can pin exact historical CVE database states deterministically.

    Args:
        sec_dir: Local git mirror path inside ``cache_dir``.
        sec_url: Remote or local ``cip-kernel-sec`` repository URL.
        sec_ref: Branch name, tag name, or full 40-char commit SHA.

    Returns:
        Lowercase 40-character ``HEAD`` git commit SHA after checkout.

    Raises:
        KernelVexError: If git sync fails or ``HEAD`` does not resolve to a SHA.
    """
    normalized_url = _normalize_sec_url(sec_url)
    sec_dir.parent.mkdir(parents=True, exist_ok=True)

    # Support either branch/tag names or pinned 40-char commit SHAs identically.
    if not (sec_dir / ".git").exists():
        if _GIT_SHA_RE.match(sec_ref):
            # git clone --branch rejects raw commit SHAs; init + depth-1 fetch works uniformly.
            _run_git(["init", str(sec_dir)])
            _run_git(["remote", "add", "origin", normalized_url], cwd=sec_dir)
            _run_git(["fetch", "--depth", "1", "origin", sec_ref], cwd=sec_dir)
            _run_git(["checkout", "--detach", "FETCH_HEAD"], cwd=sec_dir)
        else:
            _run_git(["clone", "--depth", "1", "--branch", sec_ref, normalized_url, str(sec_dir)])
    else:
        # Always update origin URL so switching mirrors or refs reuses the existing cache cleanly.
        _run_git(["remote", "set-url", "origin", normalized_url], cwd=sec_dir)
        _run_git(["fetch", "--depth", "1", "origin", sec_ref], cwd=sec_dir)
        _run_git(["checkout", "--detach", "FETCH_HEAD"], cwd=sec_dir)

    sec_commit = _run_git(["rev-parse", "HEAD"], cwd=sec_dir)
    if not _GIT_SHA_RE.match(sec_commit):
        raise KernelVexError(f"Unexpected cip-kernel-sec HEAD revision: {sec_commit!r}")
    return sec_commit.lower()


def _normalize_cve_yaml(cve_id: str, raw: Any, yaml_relpath: str) -> dict[str, Any]:
    """Normalize a parsed ``cip-kernel-sec`` YAML mapping into a canonical catalog record.

    Preserves ``yaml_relpath`` (e.g. ``issues/CVE-2024-40901.yml``) so ``analyze full``
    can forward exact relative paths to ``cve-triage triage`` without duplicating files.

    Args:
        cve_id: Validated CVE identifier (file stem).
        raw: Decoded YAML object loaded from ``cip-kernel-sec/issues/*.yml``.
        yaml_relpath: Relative path from repository root to the CVE YAML file.

    Returns:
        Canonical dictionary stored under ``catalog["cves"][cve_id]``.

    Raises:
        KernelVexError: If ``raw`` is not a YAML mapping.
    """
    if not isinstance(raw, dict):
        raise KernelVexError(f"Malformed CVE YAML in {yaml_relpath}: expected mapping")

    # Deduplicate alias IDs while preserving original ordering from YAML.
    raw_aliases = raw.get("aliases") or []
    aliases = list(dict.fromkeys(str(item) for item in raw_aliases if item))

    return {
        "name": cve_id,
        "description": str(raw.get("description") or ""),
        "aliases": aliases,
        "references": [str(item) for item in (raw.get("references") or []) if item],
        "introduced_by": raw.get("introduced-by") or {},
        "introduced_version": raw.get("introduced-version") or {},
        "fixed_by": raw.get("fixed-by") or {},
        "fixed_version": raw.get("fixed-version") or {},
        "ignore": raw.get("ignore") or {},
        "affected_files": raw.get("affected-files") or {},
        "affected_configs": raw.get("affected-configs") or {},
        "yaml_relpath": yaml_relpath,
    }


def atomic_write_json(path: Path, payload: Any) -> None:
    """Atomically write JSON via a temporary sibling file and ``os.replace``.

    Prevents truncated or partially written ``catalog.json``, report JSON, or
    ``openvex.json`` files if a CI runner is interrupted mid-write. Writing the
    temporary file in ``path.parent`` guarantees the rename stays on the same
    filesystem mount.

    Args:
        path: Final destination JSON file path.
        payload: JSON-serializable Python object (dict or list).
    """
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp_path = path.with_name(f".{path.name}.tmp.{os.getpid()}")
    try:
        tmp_path.write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")
        os.replace(tmp_path, path)
    finally:
        if tmp_path.exists():
            tmp_path.unlink(missing_ok=True)


def load_catalog(cache_dir: Path) -> dict[str, Any]:
    """Load the cached ``catalog.json`` produced by ``catalog refresh``.

    Args:
        cache_dir: Kernelvex cache root directory containing ``catalog.json``.

    Returns:
        Parsed catalog dictionary including ``sec_commit`` and ``cves``.

    Raises:
        KernelVexError: If ``catalog.json`` does not exist, fails JSON decoding,
            or has an unexpected top-level structure.
    """
    catalog_path = cache_dir / "catalog.json"
    if not catalog_path.is_file():
        raise KernelVexError(
            f"Catalog not initialized at {catalog_path}. Run 'kernelvex catalog refresh' first."
        )
    try:
        data = json.loads(catalog_path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise KernelVexError(f"Failed to read catalog {catalog_path}: {exc}") from exc

    if not isinstance(data, dict) or not isinstance(data.get("cves"), dict):
        raise KernelVexError(f"Corrupted catalog structure in {catalog_path}")
    return data


def read_sec_commit(cache_dir: Path) -> str | None:
    """Return the 40-char git SHA of the cached ``cip-kernel-sec`` checkout if present.

    Checks the live git checkout first so manual git checkouts inside cache are
    reflected accurately, falling back to ``catalog.json`` when only the catalog
    JSON artifact is available (e.g. standalone ``vex emit``).

    Args:
        cache_dir: Kernelvex cache root directory.

    Returns:
        Lowercase 40-char git SHA string, or ``None`` if no provenance is cached.
    """
    sec_dir = cache_dir / "cip-kernel-sec"
    if (sec_dir / ".git").exists():
        return _run_git(["rev-parse", "HEAD"], cwd=sec_dir).lower()
    catalog_path = cache_dir / "catalog.json"
    if catalog_path.is_file():
        try:
            data = json.loads(catalog_path.read_text(encoding="utf-8"))
            sec_commit = data.get("sec_commit")
            if isinstance(sec_commit, str) and _GIT_SHA_RE.match(sec_commit):
                return sec_commit.lower()
        except (OSError, json.JSONDecodeError):
            return None
    return None


def refresh_catalog(
    cache_dir: Path,
    sec_url: str = DEFAULT_SEC_REPO_URL,
    sec_ref: str = DEFAULT_SEC_BRANCH,
    force: bool = False,
) -> dict[str, Any]:
    """Sync ``cip-kernel-sec`` and build a versioned JSON catalog in ``cache_dir``.

    If ``catalog.json`` already corresponds to the exact same ``sec_commit`` and
    ``force`` is ``False``, the existing catalog (including any merged enrichment
    data from ``catalog merge-enrich``) is returned immediately without re-parsing
    thousands of YAML files.

    Args:
        cache_dir: Persistent cache directory storing mirror and ``catalog.json``.
        sec_url: Upstream or mirror URL for ``cip-kernel-sec``.
        sec_ref: Target branch, tag, or 40-char commit SHA.
        force: Force full YAML rebuild even when ``sec_commit`` matches cache.

    Returns:
        Normalized catalog dictionary written atomically to ``catalog.json``.

    Raises:
        KernelVexError: If git sync fails, ``issues/`` is absent, no valid CVEs exist,
            or any YAML file fails schema/syntax validation.
    """
    sec_dir = cache_dir / "cip-kernel-sec"
    sec_commit = _sync_sec_repo(sec_dir, sec_url, sec_ref)
    catalog_path = cache_dir / "catalog.json"

    # Skip expensive bulk YAML parsing when HEAD is unchanged and enrichment may be cached.
    if not force and catalog_path.is_file():
        try:
            existing = load_catalog(cache_dir)
            if existing.get("sec_commit") == sec_commit:
                return existing
        except KernelVexError:
            pass

    issues_dir = sec_dir / "issues"
    if not issues_dir.is_dir():
        raise KernelVexError(f"Missing 'issues/' directory inside {sec_dir}")

    # Sort deterministically by (year, sequence) while skipping non-CVE metadata files.
    issue_files: list[tuple[tuple[int, int], Path]] = []
    for path in issues_dir.iterdir():
        if not path.is_file() or path.suffix not in (".yml", ".yaml"):
            continue
        match = _CVE_ID_RE.match(path.stem)
        if match is None:
            continue
        issue_files.append(((int(match.group("year")), int(match.group("num"))), path))

    issue_files.sort(key=lambda item: item[0])
    if not issue_files:
        raise KernelVexError(f"No CVE YAML entries found under {issues_dir}")

    cves: dict[str, dict[str, Any]] = {}
    for _, yaml_path in issue_files:
        try:
            with yaml_path.open("r", encoding="utf-8") as handle:
                raw = yaml.load(handle, Loader=_YAML_LOADER)
        except (OSError, yaml.YAMLError) as exc:
            raise KernelVexError(f"Failed to parse {yaml_path}: {exc}") from exc
        cves[yaml_path.stem] = _normalize_cve_yaml(yaml_path.stem, raw, f"issues/{yaml_path.name}")

    catalog: dict[str, Any] = {
        "schema_version": 1,
        "sec_commit": sec_commit,
        "sec_url": sec_url,
        "sec_ref": sec_ref,
        "refreshed_at": datetime.now(UTC).isoformat(),
        "cve_count": len(cves),
        "cves": cves,
    }
    atomic_write_json(catalog_path, catalog)
    return catalog


def _merge_revision_lists(target: dict[str, list[str]], incoming: Any) -> dict[str, list[str]]:
    """Merge per-revision string lists from ``cve-triage enrich`` output.

    Preserves all existing revision keys in ``target`` while appending unseen
    file paths or Kconfig boolean formulas per revision without duplicates.

    Args:
        target: Existing ``affected_files`` or ``affected_configs`` map.
        incoming: Enriched mapping parsed from an output YAML file.

    Returns:
        Merged dictionary mapping kernel revision strings to unique value lists.
    """
    if not isinstance(incoming, dict):
        return target
    merged = {str(k): list(dict.fromkeys(str(v) for v in vals)) for k, vals in target.items()}
    for rev, vals in incoming.items():
        if not isinstance(vals, list):
            continue
        rev_key = str(rev)
        existing_list = merged.setdefault(rev_key, [])
        for val in vals:
            val_str = str(val)
            if val_str and val_str not in existing_list:
                existing_list.append(val_str)
    return merged


def merge_enriched_dir(cache_dir: Path, enriched_dir: Path) -> dict[str, Any]:
    """Merge ``affected-files`` and ``affected-configs`` from ``cve-triage enrich``.

    Args:
        cache_dir: Kernelvex cache directory containing ``catalog.json``.
        enriched_dir: Directory containing YAML files produced by ``cve-triage enrich``.

    Returns:
        Updated catalog dictionary persisted atomically to ``catalog.json``.

    Raises:
        KernelVexError: If ``catalog.json`` or ``enriched_dir`` is missing or invalid.
    """
    if not enriched_dir.is_dir():
        raise KernelVexError(f"Enriched directory does not exist: {enriched_dir}")

    catalog = load_catalog(cache_dir)
    cves = catalog["cves"]
    merged_files = 0

    for yaml_path in sorted(enriched_dir.iterdir()):
        if not yaml_path.is_file() or yaml_path.suffix not in (".yml", ".yaml"):
            continue
        if _CVE_ID_RE.match(yaml_path.stem) is None:
            continue

        try:
            with yaml_path.open("r", encoding="utf-8") as handle:
                raw = yaml.load(handle, Loader=_YAML_LOADER)
        except (OSError, yaml.YAMLError) as exc:
            raise KernelVexError(f"Failed to parse enriched YAML {yaml_path}: {exc}") from exc

        if not isinstance(raw, dict):
            raise KernelVexError(f"Malformed enriched YAML in {yaml_path}: expected mapping")

        cve_id = str(raw.get("name") or yaml_path.stem)
        if cve_id not in cves:
            # Skip enriched records absent from the active catalog without inventing entries.
            continue

        entry = cves[cve_id]
        raw_files = raw.get("affected-files") or raw.get("affected_files")
        raw_configs = raw.get("affected-configs") or raw.get("affected_configs")
        entry["affected_files"] = _merge_revision_lists(
            entry.get("affected_files") or {}, raw_files
        )
        entry["affected_configs"] = _merge_revision_lists(
            entry.get("affected_configs") or {}, raw_configs
        )
        merged_files += 1

    catalog["enriched_merged_count"] = merged_files
    catalog["enriched_merged_at"] = datetime.now(UTC).isoformat()
    atomic_write_json(cache_dir / "catalog.json", catalog)
    return catalog


def select_cves(
    catalog: dict[str, Any],
    profile: ProfileName,
    since_year: int | None = None,
    cve_ids: list[str] | None = None,
) -> list[dict[str, Any]]:
    """Filter catalog CVEs by explicit ID, minimum year, and target profile.

    Args:
        catalog: Loaded ``catalog.json`` dictionary.
        profile: Active ``"cip"`` or ``"standard"`` profile.
        since_year: Optional inclusive lower bound on the CVE year (e.g. ``2024``).
        cve_ids: Optional explicit list of CVE IDs to evaluate.

    Returns:
        Sorted list of applicable CVE records.

    Raises:
        KernelVexError: If any requested CVE ID is malformed or missing, or if the
            resulting selection is empty.
    """
    cves_map: dict[str, dict[str, Any]] = catalog["cves"]
    candidates: list[dict[str, Any]] = []

    if cve_ids:
        for raw_id in dict.fromkeys(cve_ids):
            _parse_cve_id(raw_id)
            if raw_id not in cves_map:
                raise KernelVexError(f"CVE {raw_id!r} not found in cip-kernel-sec catalog")
            candidates.append(cves_map[raw_id])
    else:
        for rec in cves_map.values():
            year, _ = _parse_cve_id(rec["name"])
            if since_year is not None and year < since_year:
                continue
            candidates.append(rec)

    selected = [rec for rec in candidates if is_cve_applicable_to_profile(rec, profile)]
    selected.sort(key=lambda rec: _parse_cve_id(rec["name"]))

    if not selected:
        raise KernelVexError(
            f"No applicable CVEs matched filters (profile={profile}, since_year={since_year})"
        )
    return selected
